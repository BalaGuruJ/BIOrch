from typing import List, Optional, Dict, Any
from enum import Enum
from pydantic import BaseModel, Field

class ResultStatus(str, Enum):
    SUCCESS = "success"
    FAILURE = "failure"
    PARTIAL = "partial"

class Result(BaseModel):
    """
    Result Contract
    Represents structured output from an agent/task.
    """
    task_id: str = Field(..., description="The ID of the task this result belongs to.")
    status: ResultStatus = Field(..., description="The outcome of the task.")
    findings: List[Dict[str, Any]] = Field(default_factory=list, description="Structured data extracted or generated by the agent.")
    artifacts: List[str] = Field(default_factory=list, description="List of file paths or URIs created/modified by the task.")
    errors: List[str] = Field(default_factory=list, description="List of error messages if the task failed or had partial success.")
    metadata: Optional[Dict[str, Any]] = Field(default=None, description="Execution metrics or other metadata.")
